package com.libman.model;

public class User8 {
    private int id;
    private String username, password, fullName, email, phoneNumber, avatar, role;

    public int getId() { return id; }                       public void setId(int id) { this.id = id; }
    public String getUsername() { return username; }        public void setUsername(String v) { username = v; }
    public String getPassword() { return password; }        public void setPassword(String v) { password = v; }
    public String getFullName() { return fullName; }        public void setFullName(String v) { fullName = v; }
    public String getEmail() { return email; }              public void setEmail(String v) { email = v; }
    public String getPhoneNumber() { return phoneNumber; }  public void setPhoneNumber(String v) { phoneNumber = v; }
    public String getAvatar() { return avatar; }            public void setAvatar(String v) { avatar = v; }
    public String getRole() { return role; }                public void setRole(String v) { role = v; }
}
